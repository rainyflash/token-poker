const CATALOGS: Readonly<Record<Language, Readonly<Record<MessageKey, string>>>> = {
  en: EN_MESSAGES,
  "zh-CN": ZH_CN_MESSAGES,
};

export function translate(
  language: Language,
  key: MessageKey,
  variables?: MessageVariables,
): string {
  const message = CATALOGS[language][key];
  if (variables === undefined) return message;
  return message.replace(/\{([A-Za-z0-9_]+)\}/gu, (placeholder, variableName: string) => {
    const value = variables[variableName];
    return value === undefined ? placeholder : String(value);
  });
}
